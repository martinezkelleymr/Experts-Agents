"""
Export the Python agents' work to the website.

The website is static (free Netlify hosting has no Python server), so this script
runs the REAL Python agents and CEO Orchestrator on the sample scenarios and saves
everything they produced into  site/data/site-data.js .

Run it again whenever you change the agents or the sample data:
    python3 scripts/export_site_data.py
"""

import copy
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from mk_agents import sample_data as data  # noqa: E402
from mk_agents.agents import ALL_AGENTS  # noqa: E402
from mk_agents.chat import SUGGESTIONS  # noqa: E402
from mk_agents.orchestrator import WORKFLOWS, CEOOrchestrator  # noqa: E402

OUTPUT = ROOT / "site" / "data" / "site-data.js"
PY_OUT = ROOT / "site" / "py" / "mk_agents"
# Python files the website loads into the browser (Pyodide) for the chat
PYTHON_FILES = ["__init__.py", "agents.py", "calculators.py", "orchestrator.py", "sample_data.py", "chat.py"]

SCENARIOS = [
    {
        "id": "house",
        "title": "Fix-and-flip or rental?",
        "tagline": "A dated 3-bedroom house in Pembroke Pines",
        "request": "Analyze this house: should we flip it or keep it as a rental?",
        "subject": data.SAMPLE_HOUSE,
    },
    {
        "id": "lot",
        "title": "What should we build?",
        "tagline": "A 10,000 sq ft vacant lot in Miami-Dade",
        "request": "Should we buy this vacant lot and what should we build on it?",
        "subject": data.SAMPLE_LOT,
    },
    {
        "id": "condo",
        "title": "Compliance check",
        "tagline": "A Miami condo that breaks company rules",
        "request": "Analyze this condo as an investment.",
        "subject": data.SAMPLE_CONDO,
    },
]


def which_demos(agent_name):
    return [kind for kind, names in WORKFLOWS.items() if agent_name in names]


def run_scenario(scenario):
    ceo = CEOOrchestrator()
    deal = ceo.handle_request(scenario["request"], copy.deepcopy(scenario["subject"]))
    recommendation = deal.memo.split("RECOMMENDATION: ")[1].split("\n")[0]
    can_approve = not deal.blocked_reason and not recommendation.startswith(("Do not", "Pass", "DO NOT"))

    after_approval = None
    if can_approve:
        approved = copy.deepcopy(deal)
        ceo.founder_decision(approved, approved=True, decided_by="Founder")
        after_approval = ceo.next_steps_after_approval(approved)

    return {
        "id": scenario["id"],
        "title": scenario["title"],
        "tagline": scenario["tagline"],
        "request": scenario["request"],
        "subject": deal.subject,
        "workflow": deal.kind,
        "team": WORKFLOWS[deal.kind],
        "activity_log": deal.activity_log,
        "reports": deal.reports,
        "memo": deal.memo,
        "recommendation": recommendation,
        "blocked_reason": deal.blocked_reason,
        "can_approve": can_approve,
        "after_approval": after_approval,
    }


def build():
    orchestrator = CEOOrchestrator()
    agents = [{"number": 0, "name": orchestrator.name, "division": "Leadership",
               "role": "The Founder's chief of staff: receives requests, assigns the right experts, "
                       "stops blocked deals and writes one Decision Memo for the Founder.",
               "responsibilities": ["Choose the workflow", "Delegate to specialists", "Stop blocked deals",
                                    "Write the Decision Memo", "Wait for the Founder's decision"],
               "instructions": orchestrator.instructions,
               "inputs": ["Founder's request", "Property or lot", "All agent reports"],
               "outputs": ["Decision Memo", "Approval request"],
               "demos": list(WORKFLOWS)}]
    for number, agent in enumerate(ALL_AGENTS, start=1):
        info = agent.describe()
        info["number"] = number
        info["demos"] = which_demos(agent.name)
        agents.append(info)
    return {
        "company": "MK.Buildings",
        "agents": agents,
        "scenarios": [run_scenario(s) for s in SCENARIOS],
        "policy": data.INVESTMENT_POLICY,
        "python_files": PYTHON_FILES,
        "chat_suggestions": SUGGESTIONS,
    }


def render(site_data):
    payload = json.dumps(site_data, indent=2, sort_keys=True)
    return ("// Generated by scripts/export_site_data.py from the Python agents. Do not edit by hand.\n"
            f"window.MKB_DATA = {payload};\n")


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(build()), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    PY_OUT.mkdir(parents=True, exist_ok=True)
    for name in PYTHON_FILES:
        (PY_OUT / name).write_text((ROOT / "mk_agents" / name).read_text(encoding="utf-8"), encoding="utf-8")
    print(f"Copied {len(PYTHON_FILES)} agent files to {PY_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
